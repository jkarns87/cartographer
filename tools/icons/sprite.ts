/**
 * Pure half of the sprite generator: parse icons.json and render Sprite.tsx text.
 * The CLI wrapper is build-sprite.ts; keeping the logic here lets tests exercise it
 * without touching the file system.
 */
import { ICON_NAMES, PATH_DATA, isRecord } from './names';
import type { IconEntry, IconName } from './names';

/** Validates the parsed icons.json shape: exactly the 15 names, each with string fields. */
export const parseIcons = (
  raw: unknown,
  label = 'icons.json'
): Map<IconName, IconEntry> => {
  if (!isRecord(raw))
    throw new Error(`${label}: expected an object at the top level`);
  const known = new Set<string>(ICON_NAMES);
  for (const key of Object.keys(raw)) {
    if (!known.has(key))
      throw new Error(`${label}: "${key}" is not a LandmarkId or "tent"`);
  }
  const icons = new Map<IconName, IconEntry>();
  for (const name of ICON_NAMES) {
    const entry = raw[name];
    if (!isRecord(entry))
      throw new Error(`${label}: missing entry for "${name}"`);
    const { path, author, source } = entry;
    if (
      typeof path !== 'string' ||
      typeof author !== 'string' ||
      typeof source !== 'string'
    ) {
      throw new Error(
        `${label}: "${name}" must have string path, author and source`
      );
    }
    if (!PATH_DATA.test(path)) {
      throw new Error(`${label}: "${name}" has unexpected characters in path`);
    }
    icons.set(name, { path, author, source });
  }
  return icons;
};

const renderSymbol = (name: IconName, path: string): string =>
  [
    `    <symbol id="ic-${name}" viewBox="0 0 512 512">`,
    `      <path d="${path}" />`,
    `    </symbol>`,
  ].join('\n');

/** Renders the full Sprite.tsx source. Symbols are sorted by name so output is stable. */
export const renderSprite = (icons: Map<IconName, IconEntry>): string => {
  const names = [...icons.keys()].sort();
  const symbols = names
    .map((name) => renderSymbol(name, icons.get(name)?.path ?? ''))
    .join('\n');
  const authors = [...new Set([...icons.values()].map((e) => e.author))]
    .sort()
    .join(' and ');
  return `// Generated by tools/icons/build-sprite.ts from src/client/icons/icons.json. Do not edit by hand.
// Icons by ${authors}, game-icons.net, CC BY 3.0. See ATTRIBUTION.md.

/**
 * Inline SVG sprite. Mount it once near the root of each entry point that renders an
 * \`Icon\`; \`Icon\` draws its glyph with <use href="#ic-<name>" />.
 */
export const Sprite = () => (
  <svg width="0" height="0" style={{ position: 'absolute' }} aria-hidden="true">
${symbols}
  </svg>
);
`;
};
